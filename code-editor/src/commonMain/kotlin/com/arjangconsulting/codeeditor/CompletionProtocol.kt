package com.arjangconsulting.codeeditor

import androidx.compose.runtime.Immutable
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.Json

/**
 * Runtime identity captured by a completion provider.
 *
 * @property sessionId Host-owned session identity, including for an external add-on.
 * @property revision Increment after execution, device changes, or other runtime context changes.
 * @property attributes Opaque routing information, such as a device or workspace ID. Keep credentials
 *   in the transport configuration. Treat this map as immutable after construction.
 */
@Immutable
@Serializable
public data class CompletionContext(
    val sessionId: String,
    val revision: Long = 0,
    val attributes: Map<String, String> = emptyMap(),
) {
    init {
        require(sessionId.isNotBlank()) { "sessionId must not be blank" }
        require(revision >= 0) { "revision must be nonnegative" }
    }
}

/**
 * Transport-independent completion request, usable in-process or through [CompletionProtocol].
 *
 * @property requestId Unique correlation ID generated by the editor adapter.
 * @property context Runtime context captured for this request.
 * @property languageId Host-selected language or command dialect.
 * @property text Full editable document, excluding transcript and runtime output.
 * @property documentVersion Version of [text]; echoed by the response.
 * @property position Zero-based caret position with UTF-16 character offsets.
 * @property trigger Why suggestions were requested.
 * @property protocolVersion Completion protocol major version; currently 1.
 */
@Immutable
@Serializable
public data class CompletionRequest(
    val requestId: String,
    val context: CompletionContext,
    val languageId: String,
    val text: String,
    val documentVersion: Long,
    val position: TextPosition,
    val trigger: CompletionTrigger,
    val protocolVersion: Int = CompletionProtocol.VERSION,
) {
    init {
        require(requestId.isNotBlank()) { "requestId must not be blank" }
        require(languageId.isNotBlank()) { "languageId must not be blank" }
        require(documentVersion >= 0) { "documentVersion must be nonnegative" }
        val snapshot = DocumentSnapshot(text, documentVersion)
        require(snapshot.positionOf(snapshot.offsetOf(position)) == position) { "position must be inside text" }
    }

    /** Creates a response with this request's correlation and version information. */
    public fun response(completions: CompletionList?): CompletionResponse = CompletionResponse(
        requestId = requestId,
        sessionId = context.sessionId,
        contextRevision = context.revision,
        documentVersion = documentVersion,
        completions = completions,
        protocolVersion = protocolVersion,
    )
}

/**
 * Correlated completion result. All edits use the original request's text and UTF-16 coordinates.
 *
 * @property requestId Echo of the request ID.
 * @property sessionId Echo of the requested session ID.
 * @property contextRevision Echo of the requested runtime revision.
 * @property documentVersion Echo of the requested document version.
 * @property completions Suggestions; null means unsupported/unavailable, empty means no suggestions.
 * @property protocolVersion Completion protocol major version; currently 1.
 */
@Immutable
@Serializable
public data class CompletionResponse(
    val requestId: String,
    val sessionId: String,
    val contextRevision: Long,
    val documentVersion: Long,
    val completions: CompletionList?,
    val protocolVersion: Int = CompletionProtocol.VERSION,
)

/**
 * Versioned JSON codec for native providers and external completion add-ons.
 *
 * Fields use the Kotlin model names, enum values use their SCREAMING_CASE names, and edit ranges
 * contain `start`/`end` positions. Unknown fields are ignored for additive compatibility. Missing
 * optional fields use model defaults; unsupported major versions are rejected. Transport framing,
 * authentication, connection lifecycle, request routing, and cancellation belong to the host.
 */
public object CompletionProtocol {
    /** Current completion protocol major version. */
    public const val VERSION: Int = 1

    private val json = Json {
        ignoreUnknownKeys = true
        encodeDefaults = true
    }

    /** Encodes a request, rejecting unsupported protocol versions. */
    public fun encodeRequest(request: CompletionRequest): String {
        requireVersion(request.protocolVersion)
        return json.encodeToString(request)
    }

    /** Decodes and validates a request, rejecting malformed input or unsupported versions. */
    public fun decodeRequest(value: String): CompletionRequest =
        json.decodeFromString<CompletionRequest>(value).also { requireVersion(it.protocolVersion) }

    /** Encodes a response, rejecting unsupported protocol versions. */
    public fun encodeResponse(response: CompletionResponse): String {
        requireVersion(response.protocolVersion)
        return json.encodeToString(response)
    }

    /** Decodes a response, rejecting malformed input or unsupported versions. */
    public fun decodeResponse(value: String): CompletionResponse =
        json.decodeFromString<CompletionResponse>(value).also { requireVersion(it.protocolVersion) }

    private fun requireVersion(version: Int) {
        require(version == VERSION) { "Unsupported completion protocol version: $version" }
    }
}
